#!/usr/bin/env bash
set -euo pipefail

ARTIFACT_ROOT=/opt/hosteye/artifacts
SOURCE_DIR="$ARTIFACT_ROOT/VectorBuild"
INSTALLER_ROOT="$ARTIFACT_ROOT/installers"
PACKAGE_DIR="$INSTALLER_ROOT/HostEye-Agent-Installer"
CERT_DIR="$PACKAGE_DIR/certs"
ZIP_PATH="$INSTALLER_ROOT/HostEye-Agent-Installer.zip"

mkdir -p "$INSTALLER_ROOT"
rm -rf "$PACKAGE_DIR" "$ZIP_PATH"
mkdir -p "$PACKAGE_DIR" "$CERT_DIR"

if [ -d "$SOURCE_DIR" ]; then
  cp -a "$SOURCE_DIR"/. "$PACKAGE_DIR"/
fi

rm -rf "$PACKAGE_DIR/SOCShipper/bin" "$PACKAGE_DIR/SOCShipper/obj"
find "$PACKAGE_DIR" -type f -name '*.pdb' -delete

cp /opt/hosteye/certs/hosteye-local-ca.crt "$CERT_DIR/company_ca.crt"
cp /opt/hosteye/certs/client.crt "$CERT_DIR/client.crt"
cp /opt/hosteye/certs/client.key "$CERT_DIR/client.key"

cat >"$PACKAGE_DIR/install-lab.ps1" <<'EOF'
param(
    [string]$GatewayUri = "https://hosteye.iahn.hanoi.vn/api/v1/telemetry",
    [switch]$NoStart
)

$ErrorActionPreference = "Stop"
$installer = Join-Path $PSScriptRoot "install.ps1"
if (-not (Test-Path $installer)) {
    throw "install.ps1 was not found next to install-lab.ps1"
}

$argsList = @(
    "-ExecutionPolicy", "Bypass",
    "-File", $installer,
    "-GatewayUri", $GatewayUri,
    "-CaCertificateFileName", "company_ca.crt"
)
if ($NoStart) {
    $argsList += "-NoStart"
}

& powershell.exe @argsList
exit $LASTEXITCODE
EOF

cat >"$PACKAGE_DIR/README-LAB.txt" <<'EOF'
HostEye lab installer

Run PowerShell as Administrator, then:

  .\install-lab.ps1

Default telemetry endpoint:

  https://hosteye.iahn.hanoi.vn/api/v1/telemetry

If the endpoint machine is not the Docker host, pass the reachable Docker host name or IP:

  .\install-lab.ps1 -GatewayUri "https://<docker-host>/api/v1/telemetry"

The bundled certs\company_ca.crt is the lab CA generated by the all-in-one container.
The bundled certs\client.crt and certs\client.key are a lab client certificate pair.
The installer imports the CA into LocalMachine Root before starting HostEye.
EOF

(
  cd "$INSTALLER_ROOT"
  zip -qr "$(basename "$ZIP_PATH")" "$(basename "$PACKAGE_DIR")"
)

echo "HostEye lab installer package ready: $ZIP_PATH"
